// Prepare a release: node scripts/release.mjs <version> ["note" ...] [--min-app=x.y.z] [--min-native=N] [--apk-url=URL]
// Writes public/js/version.js, public/version.json (with SHA-256 of every shipped file) and stamps
// public/sw.js. Then deploy with `npm run deploy`. Installed apps pick the release up by themselves.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

const args = process.argv.slice(2), opt = k => (args.find(a => a.startsWith(`--${k}=`)) || "").split("=").slice(1).join("=");
const DIR = opt("dir") || "public";
const SKIP = new Set(["version.json"]);
const walk = d => readdirSync(d).flatMap(f => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const listFiles = () => walk(DIR).map(p => relative(DIR, p).split("\\").join("/")).filter(p => !SKIP.has(p) && !p.split("/").some(s => s.startsWith("."))).sort()
  .map(p => { const b = readFileSync(join(DIR, p)); return { p, h: createHash("sha256").update(b).digest("hex"), s: b.length }; });

if (args.includes("--verify")) {
  // Fails if any shipped file changed after `npm run release` (the APK live update would reject it).
  const m = JSON.parse(readFileSync(join(DIR, "version.json"), "utf8")), now = listFiles();
  const want = new Map(m.files.map(f => [f.p, f.h])), bad = [];
  for (const f of now) if (want.get(f.p) !== f.h) bad.push(f.p);
  for (const p of want.keys()) if (!now.some(f => f.p === p)) bad.push(p + " (missing)");
  const vjs = readFileSync(join(DIR, "js/version.js"), "utf8"), sw = readFileSync(join(DIR, "sw.js"), "utf8");
  if (!vjs.includes(`"version":"${m.version}","build":"${m.build}"`)) bad.push("js/version.js does not match version.json");
  if (!sw.includes(`const VERSION = "hmtp-${m.version}+${m.build}";`)) bad.push("sw.js VERSION does not match version.json");
  if (bad.length) { console.error("Release manifest is stale. Run `npm run release -- <version> \"notes\"` again.\n  " + bad.join("\n  ")); process.exit(1); }
  console.log(`release ${m.version} (${m.build}) verified: ${now.length} files`); process.exit(0);
}
const version = args[0], notes = args.slice(1).filter(a => !a.startsWith("--"));
if (!/^\d+\.\d+\.\d+$/.test(version || "")) { console.error("usage: npm run release -- 3.1.0 \"catatan perubahan\" [--min-app=3.0.0] [--min-native=1]"); process.exit(1); }
const prev = (() => { try { return JSON.parse(readFileSync(join(DIR, "version.json"), "utf8")); } catch { return {}; } })();
const build = new Date().toISOString().replace(/\.\d+Z$/, "Z");
const minNative = +(opt("min-native") || prev.minNative || 1), minApp = opt("min-app") || prev.minApp || "3.0.0";
const apkUrl = opt("apk-url") || prev.apkUrl || "https://github.com/rawsushies/hm-training-plan/releases/latest";

writeFileSync(join(DIR, "js/version.js"), `/* Generated by scripts/release.mjs. The build that is running. */\nwindow.HMTP_BUILD = ${JSON.stringify({ version, build })};\n`);
const sw = readFileSync(join(DIR, "sw.js"), "utf8").replace(/const VERSION = "[^"]*";/, `const VERSION = "hmtp-${version}+${build}";`);
writeFileSync(join(DIR, "sw.js"), sw);

const files = listFiles();
const manifest = { version, build, minApp, minNative, apkUrl, notes, files };
writeFileSync(join(DIR, "version.json"), JSON.stringify(manifest, null, 1) + "\n");
if (DIR === "public") { const pkg = JSON.parse(readFileSync("package.json", "utf8")); pkg.version = version; writeFileSync("package.json", JSON.stringify(pkg, null, 2) + "\n"); }
console.log(`release ${version} (${build}): ${files.length} files, ${(files.reduce((a, f) => a + f.s, 0) / 1024).toFixed(0)} KB, minApp ${minApp}, minNative ${minNative}`);
